#!/usr/bin/env php
<?php
declare(strict_types=1);

/**
 * Build deterministic cycle-encoding corpora test_files180 through test_files195.
 *
 * Recipes live in cycle_encoding_recipes.php for generation and verification only.
 * They are not compression hints and must not be used by fz search.
 *
 * Usage from repo root:
 *   php benchmarks/build_test_files180_193.php
 */

$root = realpath(dirname(__DIR__)) ?: dirname(__DIR__);
require_once $root . DIRECTORY_SEPARATOR . 'cycle_encoding_recipes.php';

function cycle_fixture_put(string $base, string $rel, string $bytes): void
{
	$p = $base . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $rel);
	$dir = dirname($p);
	if(!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
		throw new RuntimeException('mkdir failed: ' . $dir);
	}
	if(file_put_contents($p, $bytes) === false) {
		throw new RuntimeException('write failed: ' . $p);
	}
}

function cycle_fixture_rmtree(string $dir): void
{
	if(!is_dir($dir)) {
		return;
	}
	$it = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
		RecursiveIteratorIterator::CHILD_FIRST
	);
	foreach($it as $item) {
		if($item->isDir()) {
			@rmdir($item->getPathname());
		} else {
			@unlink($item->getPathname());
		}
	}
	@rmdir($dir);
}

/**
 * @param array<string,mixed> $spec
 */
function cycle_fixture_readme(int $case, array $spec): string
{
	$width = (int)($spec['width'] ?? 1);
	$version = (int)($spec['version'] ?? 2);
	$lines = array(
		"test_files{$case} - cycle epicycle v{$version} fixture",
		"",
		"Purpose: " . (string)$spec['note'],
		"Tier: " . (string)$spec['tier'],
		"Representation: " . (string)$spec['representation'],
		"combine=" . (string)($spec['combine'] ?? 'single')
			. " byte_map=" . (string)($spec['byte_map'] ?? 'direct')
			. " length=" . (string)$spec['length']
			. ($width > 1 ? ' width=' . (string)$width : ''),
		"",
		"Generated by benchmarks/build_test_files180_193.php.",
		"Recipes are recorded in cycle_encoding_recipes.php only for fixture regeneration and verification.",
		"They must not be used as compression hints, oracle rows, or case-specific shortcuts.",
		"",
		"Files:",
		"  - " . (string)$spec['file'] . " bytes=" . (string)$spec['expected_size']
			. " xxh128=" . (string)$spec['expected_xxh128'],
	);
	return implode("\n", $lines) . "\n";
}

$specs = cycle_encoding_expanded_specs();

$fpLines = array(
	'<?php',
	'declare(strict_types=1);',
	'',
	'/**',
	' * Fixture xxh128 fingerprints for test_files180-195 (auto-generated).',
	' *',
	' * Regenerate: php benchmarks/build_test_files180_193.php',
	' */',
	'',
	'/**',
	' * @return array<int,string> case => xxh128 hex',
	' */',
	'function cycle_encoding_fixture_fingerprints(): array',
	'{',
	'	return array(',
);
foreach($specs as $case => $spec) {
	$fpLines[] = "\t\t" . (int)$case . " => '" . (string)$spec['expected_xxh128'] . "',";
}
$fpLines[] = "\t);";
$fpLines[] = "}";
$fpLines[] = "";
$fpPath = $root . DIRECTORY_SEPARATOR . 'cycle_encoding_fingerprints.php';
if(file_put_contents($fpPath, implode("\n", $fpLines)) === false) {
	throw new RuntimeException('write failed: ' . $fpPath);
}
fwrite(STDOUT, 'updated cycle_encoding_fingerprints.php' . "\n");

foreach($specs as $case => $spec) {
	$dir = $root . DIRECTORY_SEPARATOR . (string)$spec['dir'];
	cycle_fixture_rmtree($dir);
	if(!mkdir($dir, 0755, true) && !is_dir($dir)) {
		throw new RuntimeException('mkdir failed: ' . $dir);
	}
	cycle_fixture_put($dir, '00_README_corpus.txt', cycle_fixture_readme((int)$case, $spec));
	cycle_fixture_put($dir, (string)$spec['file'], (string)$spec['bytes']);
	fwrite(STDOUT, 'built ' . (string)$spec['dir'] . ' bytes=' . (string)$spec['expected_size']
		. ' xxh128=' . (string)$spec['expected_xxh128'] . "\n");
}

fwrite(STDOUT, "built test_files180-195\n");

$fieldsPath = $root . DIRECTORY_SEPARATOR . 'test_files110' . DIRECTORY_SEPARATOR . 'fields.c';
if(is_file($fieldsPath) && isset(cycle_encoding_recipe_specs()[184])) {
	$hybridDir = $root . DIRECTORY_SEPARATOR . 'test_files196';
	cycle_fixture_rmtree($hybridDir);
	if(!mkdir($hybridDir, 0755, true) && !is_dir($hybridDir)) {
		throw new RuntimeException('mkdir failed: ' . $hybridDir);
	}
	$fields = (string)file_get_contents($fieldsPath);
	$cyclePart = cycle_encoding_generate(cycle_encoding_recipe_specs()[184]);
	$hybrid = substr($fields, 0, 8000) . $cyclePart;
	cycle_fixture_put($hybridDir, 'hybrid.txt', $hybrid);
	$readme = implode("\n", array(
		'test_files196 - hybrid natural prefix + cycle suffix',
		'',
		'Purpose: fields.c first 8000 B + test_files184 cycle (10 KiB RR).',
		'Expect: cycle_inner segmented WIN vs gz9 on full hybrid.',
		'bytes=' . (string)strlen($hybrid) . ' xxh128=' . hash('xxh128', $hybrid, false),
		'',
	)) . "\n";
	cycle_fixture_put($hybridDir, '00_README_corpus.txt', $readme);
	fwrite(STDOUT, 'built test_files196 hybrid bytes=' . (string)strlen($hybrid) . "\n");
}

if(is_file($fieldsPath) && isset(cycle_encoding_recipe_specs()[194])) {
	$hybridDir = $root . DIRECTORY_SEPARATOR . 'test_files197';
	cycle_fixture_rmtree($hybridDir);
	if(!mkdir($hybridDir, 0755, true) && !is_dir($hybridDir)) {
		throw new RuntimeException('mkdir failed: ' . $hybridDir);
	}
	$fields = (string)file_get_contents($fieldsPath);
	$cyclePart = cycle_encoding_generate(cycle_encoding_recipe_specs()[194]);
	$hybrid = substr($fields, 0, 8000) . $cyclePart;
	cycle_fixture_put($hybridDir, 'hybrid.txt', $hybrid);
	$readme = implode("\n", array(
		'test_files197 - hybrid natural prefix + 1 MiB torus-single cycle',
		'',
		'Purpose: fields.c first 8000 B + test_files194 torus-single (1 MiB).',
		'Expect: cycle_inner segmented WIN vs gz9; scales 196 pattern to 1 MiB cycle tail.',
		'bytes=' . (string)strlen($hybrid) . ' xxh128=' . hash('xxh128', $hybrid, false),
		'',
	)) . "\n";
	cycle_fixture_put($hybridDir, '00_README_corpus.txt', $readme);
	fwrite(STDOUT, 'built test_files197 hybrid bytes=' . (string)strlen($hybrid) . "\n");
}
