#!/usr/bin/env php
<?php
declare(strict_types=1);

/**
 * Build deterministic fractal-inner stress corpora test_files140 through test_files150.
 *
 * Recipes live in benchmarks/fractal_inner_recipes_140_150.php for generation and
 * verification only. They are not compression hints and must not be used by fz search.
 *
 * Usage from repo root:
 *   php benchmarks/build_test_files140_150.php
 */

putenv('FRACTAL_ZIP_SUPPRESS_HTML=1');

$root = realpath(dirname(__DIR__)) ?: dirname(__DIR__);
require_once $root . DIRECTORY_SEPARATOR . 'fractal_zip.php';
require_once __DIR__ . DIRECTORY_SEPARATOR . 'fractal_inner_recipes_140_150.php';

function fz_inner_fixture_put(string $base, string $rel, string $bytes): void
{
	$p = $base . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $rel);
	$dir = dirname($p);
	if(!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
		throw new RuntimeException('mkdir failed: ' . $dir);
	}
	if(file_put_contents($p, $bytes) === false) {
		throw new RuntimeException('write failed: ' . $p);
	}
}

function fz_inner_fixture_rmtree(string $dir): void
{
	if(!is_dir($dir)) {
		return;
	}
	$it = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS),
		RecursiveIteratorIterator::CHILD_FIRST
	);
	foreach($it as $item) {
		if($item->isDir()) {
			@rmdir($item->getPathname());
		} else {
			@unlink($item->getPathname());
		}
	}
	@rmdir($dir);
}

function fz_inner_fixture_readme(int $case, array $spec): string
{
	$ops = implode(', ', $spec['operations']);
	$lines = array(
		"test_files{$case} - fractal inner stress fixture",
		"",
		"Purpose: " . $spec['note'],
		"Operations: " . $ops,
		"",
		"Generated by benchmarks/build_test_files140_150.php.",
		"Recipes are recorded in benchmarks/fractal_inner_recipes_140_150.php only for fixture regeneration and verification.",
		"They must not be used as compression hints, oracle rows, or case-specific shortcuts.",
		"",
		"Files:",
	);
	foreach($spec['files'] as $file) {
		$lines[] = "  - " . $file['path'] . " bytes=" . (string)$file['expected_size'] . " xxh128=" . $file['expected_xxh128'];
	}
	return implode("\n", $lines) . "\n";
}

$fz = new fractal_zip(64, false, false, null, false);
$specs = fz_inner_fixture_expanded_specs_140_150($fz);

foreach($specs as $case => $spec) {
	$dir = $root . DIRECTORY_SEPARATOR . $spec['dir'];
	fz_inner_fixture_rmtree($dir);
	if(!mkdir($dir, 0755, true) && !is_dir($dir)) {
		throw new RuntimeException('mkdir failed: ' . $dir);
	}
	fz_inner_fixture_put($dir, '00_README_corpus.txt', fz_inner_fixture_readme((int)$case, $spec));
	foreach($spec['files'] as $file) {
		$bytes = fz_inner_fixture_expand_recipe($fz, $file['recipe']);
		fz_inner_fixture_put($dir, (string)$file['path'], $bytes);
	}
	fwrite(STDOUT, 'built ' . $spec['dir'] . ' files=' . (string)count($spec['files']) . "\n");
}

fwrite(STDOUT, "built test_files140-150\n");
